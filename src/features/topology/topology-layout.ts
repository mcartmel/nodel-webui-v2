import type { TopologyCanvasNode, TopologyCanvasPoint, TopologyCanvasViewport, TopologyCanvasWire } from './topology-canvas';
import type { TopologyNodeId } from './topology-model';

export type TopologyWorkspaceMode = 'all' | 'custom';

export interface TopologyLayoutPreferences {
  query?: string;
  host?: string;
  readability?: string;
  [key: string]: boolean | number | string | undefined;
}

export interface TopologyFocusRestoreState {
  selectedNodeId: TopologyNodeId;
  previousMode: 'detailed' | 'overview' | 'compact' | 'all-nodes';
  previousSelectionType?: 'node' | 'binding';
  previousSelectionId?: string;
  previousViewport?: TopologyCanvasViewport;
}

export interface TopologySavedSelection {
  type: 'node' | 'binding';
  id: string;
}

export interface TopologyLayout {
  positions: ReadonlyMap<TopologyNodeId, TopologyCanvasPoint>;
  /** Coordinates generated by placement, distinct from dragged/manual anchors. */
  autoPositionedNodeIds?: ReadonlySet<TopologyNodeId>;
  focusRestoreState?: TopologyFocusRestoreState;
  viewport?: TopologyCanvasViewport;
  /** User-selected membership, retained even when an inventory read is partial. */
  pinnedNodeIds?: ReadonlySet<TopologyNodeId>;
  /** Explicit exclusions used only by the `all` workspace mode. */
  omittedNodeIds?: ReadonlySet<TopologyNodeId>;
  selectedNodeId?: TopologyNodeId;
  selectedSelection?: TopologySavedSelection;
  workspaceMode?: TopologyWorkspaceMode;
  preferences?: TopologyLayoutPreferences;
}

const STORAGE_PREFIX = 'nodel.topology.layout.v2:';
const LEGACY_STORAGE_PREFIX = 'nodel.topology.layout.v1:';
const MAX_COORDINATE = 1_000_000;
const MAX_STORED_POSITIONS = 2048;
const MAX_STORED_MEMBERSHIP = 2048;
// Keep the serialized payload below the reader limit with room for future
// envelope changes. Automatic positions are expendable; user-authored state is not.
const MAX_SERIALIZED_LAYOUT = 190_000;
const MAX_PREFERENCES = 64;
const MAX_PREFERENCE_TEXT = 512;
const MAX_LAYOUT_NODES = 1000;
const MAX_LAYOUT_WIRES = 5000;

// Keep collision checks aligned with the actual X6 rectangle dimensions in
// topology-canvas.ts. Positions are the node's top-left corner.
export const TOPOLOGY_NODE_BOUNDS = { width: 248, height: 160 } as const;
const NODE_LAYOUT_GAP = 24;
const TOPOLOGY_NODE_WIDTH = 248;

/** Evidence header divider is at 82px; sockets use 24px rows below that header. */
export function topologyNodeHeight(portCount: number): number {
  const rows = Number.isFinite(portCount) ? Math.max(0, Math.ceil(portCount)) : 0;
  return Math.max(106, 94 + rows * 24);
}

/** Exact dimensions used by the canvas for a node with the given projected endpoint count. */
export function topologyNodeSize(portCount: number): { width: number; height: number } {
  return { width: TOPOLOGY_NODE_WIDTH, height: topologyNodeHeight(portCount) };
}

function validPoint(value: unknown): value is TopologyCanvasPoint {
  if (!value || typeof value !== 'object') return false;
  const point = value as Record<string, unknown>;
  return typeof point.x === 'number' && Number.isFinite(point.x) && Math.abs(point.x) <= MAX_COORDINATE
    && typeof point.y === 'number' && Number.isFinite(point.y) && Math.abs(point.y) <= MAX_COORDINATE;
}

function validViewport(value: unknown): value is TopologyCanvasViewport {
  if (!value || typeof value !== 'object') return false;
  const viewport = value as Record<string, unknown>;
  return typeof viewport.x === 'number' && Number.isFinite(viewport.x) && Math.abs(viewport.x) <= MAX_COORDINATE
    && typeof viewport.y === 'number' && Number.isFinite(viewport.y) && Math.abs(viewport.y) <= MAX_COORDINATE
    && typeof viewport.scale === 'number' && Number.isFinite(viewport.scale) && viewport.scale >= 0.25 && viewport.scale <= 2.5;
}

export function topologyLayoutStorageKey(hostContext: string): string {
  return `${STORAGE_PREFIX}${encodeURIComponent(hostContext)}`;
}

export function legacyTopologyLayoutStorageKey(hostContext: string): string {
  return `${LEGACY_STORAGE_PREFIX}${encodeURIComponent(hostContext)}`;
}

function readIds(value: unknown): Set<TopologyNodeId> {
  if (!Array.isArray(value)) return new Set();
  return new Set(value.slice(0, MAX_STORED_MEMBERSHIP).filter((id): id is string => typeof id === 'string' && id.length > 0 && id.length <= 4096) as TopologyNodeId[]);
}

function readPreferences(value: unknown): TopologyLayoutPreferences | undefined {
  if (!value || typeof value !== 'object' || Array.isArray(value)) return undefined;
  const result: TopologyLayoutPreferences = {};
  for (const [key, item] of Object.entries(value as Record<string, unknown>).slice(0, MAX_PREFERENCES)) {
    if (!key || key.length > 80) continue;
    if (typeof item === 'boolean') result[key] = item;
    else if (typeof item === 'number' && Number.isFinite(item)) result[key] = item;
    else if (typeof item === 'string' && item.length <= MAX_PREFERENCE_TEXT) result[key] = item;
  }
  return result;
}

export function readTopologyLayout(hostContext: string, storage?: Pick<Storage, 'getItem'>): TopologyLayout {
  try {
    const target = storage ?? window.localStorage;
    // v1 persisted only positions and camera. Keep those manual placements
    // while upgrading to v2; never migrate another host's state.
    const raw = target.getItem(topologyLayoutStorageKey(hostContext)) ?? target.getItem(legacyTopologyLayoutStorageKey(hostContext));
    if (!raw || raw.length > 200_000) return { positions: new Map() };
    const value = JSON.parse(raw) as Record<string, unknown>;
    const positions = new Map<TopologyNodeId, TopologyCanvasPoint>();
    if (value.positions && typeof value.positions === 'object' && !Array.isArray(value.positions)) {
      for (const [id, point] of Object.entries(value.positions as Record<string, unknown>).slice(0, MAX_STORED_POSITIONS)) {
        if (id.length <= 4096 && validPoint(point)) positions.set(id as TopologyNodeId, { x: point.x, y: point.y });
      }
    }
    const pinnedNodeIds = readIds(value.pinnedNodeIds);
    const autoPositionedNodeIds = readIds(value.autoPositionedNodeIds);
    const omittedNodeIds = readIds(value.omittedNodeIds);
    const workspaceMode = value.workspaceMode === 'all' || value.workspaceMode === 'custom' ? value.workspaceMode : undefined;
    const preferences = readPreferences(value.preferences);
    const selection = value.selectedSelection && typeof value.selectedSelection === 'object' ? value.selectedSelection as Record<string, unknown> : undefined;
    const selectionType: TopologySavedSelection['type'] | undefined = selection?.type === 'node' ? 'node' : selection?.type === 'binding' ? 'binding' : undefined;
    const selectedSelection: TopologySavedSelection | undefined = selection && selectionType && typeof selection.id === 'string' && selection.id.length > 0 && selection.id.length <= 4096
      ? { type: selectionType, id: selection.id } : undefined;
    const focus = value.focusRestoreState && typeof value.focusRestoreState === 'object' ? value.focusRestoreState as Record<string, unknown> : undefined;
    const focusRestoreState = focus && typeof focus.selectedNodeId === 'string' && focus.selectedNodeId.length <= 4096
      && ['detailed', 'overview', 'compact', 'all-nodes'].includes(String(focus.previousMode))
      ? { selectedNodeId: focus.selectedNodeId as TopologyNodeId, previousMode: focus.previousMode as TopologyFocusRestoreState['previousMode'],
        ...(focus.previousSelectionType === 'node' || focus.previousSelectionType === 'binding' ? { previousSelectionType: focus.previousSelectionType } : {}),
        ...(typeof focus.previousSelectionId === 'string' && focus.previousSelectionId.length <= 4096 ? { previousSelectionId: focus.previousSelectionId } : {}),
        ...(validViewport(focus.previousViewport) ? { previousViewport: { ...focus.previousViewport } } : {}) } satisfies TopologyFocusRestoreState : undefined;
    return { positions, ...(validViewport(value.viewport) ? { viewport: { ...value.viewport } } : {}),
      ...(pinnedNodeIds.size ? { pinnedNodeIds } : {}), ...(omittedNodeIds.size ? { omittedNodeIds } : {}),
      ...(autoPositionedNodeIds.size ? { autoPositionedNodeIds } : {}),
      ...(focusRestoreState ? { focusRestoreState } : {}),
      ...(selectedSelection ? { selectedSelection } : {}),
      ...(typeof value.selectedNodeId === 'string' && value.selectedNodeId.length <= 4096 ? { selectedNodeId: value.selectedNodeId as TopologyNodeId } : {}),
      ...(workspaceMode ? { workspaceMode } : {}), ...(preferences && Object.keys(preferences).length ? { preferences } : {}) };
  } catch {
    return { positions: new Map() };
  }
}

export function writeTopologyLayout(hostContext: string, layout: TopologyLayout, storage?: Pick<Storage, 'setItem'>): boolean {
  const validPositions = Array.from(layout.positions).filter(([id, point]) => id.length > 0 && id.length <= 4096 && validPoint(point));
  const automaticIds = layout.autoPositionedNodeIds ?? new Set<TopologyNodeId>();
  const manualPositions = validPositions.filter(([id]) => !automaticIds.has(id)).slice(0, MAX_STORED_POSITIONS);
  const automaticPositions = validPositions.filter(([id]) => automaticIds.has(id)).slice(0, MAX_STORED_POSITIONS);
  const viewport = validViewport(layout.viewport) ? layout.viewport : undefined;
  const pinnedNodeIds = [...(layout.pinnedNodeIds ?? [])].filter((id) => id.length > 0 && id.length <= 4096).slice(0, MAX_STORED_MEMBERSHIP);
  const omittedNodeIds = [...(layout.omittedNodeIds ?? [])].filter((id) => id.length > 0 && id.length <= 4096).slice(0, MAX_STORED_MEMBERSHIP);
  const preferences = readPreferences(layout.preferences);
  const focus = layout.focusRestoreState;
  const selection = layout.selectedSelection && layout.selectedSelection.id.length <= 4096 ? layout.selectedSelection : undefined;
  const base = { ...(viewport ? { viewport } : {}),
       ...(pinnedNodeIds.length ? { pinnedNodeIds } : {}), ...(omittedNodeIds.length ? { omittedNodeIds } : {}),
       ...(focus ? { focusRestoreState: { selectedNodeId: focus.selectedNodeId, previousMode: focus.previousMode,
         ...(focus.previousSelectionType ? { previousSelectionType: focus.previousSelectionType } : {}),
         ...(focus.previousSelectionId ? { previousSelectionId: focus.previousSelectionId } : {}),
         ...(validViewport(focus.previousViewport) ? { previousViewport: focus.previousViewport } : {}) } } : {}),
       ...(selection ? { selectedSelection: { type: selection.type, id: selection.id } } : {}),
       ...(layout.selectedNodeId && layout.selectedNodeId.length <= 4096 ? { selectedNodeId: layout.selectedNodeId } : {}),
       ...(layout.workspaceMode ? { workspaceMode: layout.workspaceMode } : {}),
       ...(preferences && Object.keys(preferences).length ? { preferences } : {}) };
  const positions: Record<string, TopologyCanvasPoint> = {};
  const autoIds = [...automaticIds].filter((id) => id.length > 0 && id.length <= 4096).slice(0, MAX_STORED_MEMBERSHIP);
  const serialize = () => JSON.stringify({ positions, ...(autoIds.length ? { autoPositionedNodeIds: autoIds } : {}), ...base });
  try {
    // If the non-regenerable state cannot fit, do not claim a successful save.
    for (const [id, point] of manualPositions) positions[id] = { x: point.x, y: point.y };
    let raw = serialize();
    // Automatic identity markers are also regenerable. Shed them before ever
    // dropping manual coordinates or user-selected state.
    while (raw.length > MAX_SERIALIZED_LAYOUT && autoIds.length) {
      autoIds.pop();
      raw = serialize();
    }
    if (raw.length > MAX_SERIALIZED_LAYOUT) return false;
    for (const [id, point] of automaticPositions) {
      positions[id] = { x: point.x, y: point.y };
      raw = serialize();
      if (raw.length > MAX_SERIALIZED_LAYOUT) {
        delete positions[id];
        raw = serialize();
        break;
      }
    }
    (storage ?? window.localStorage).setItem(topologyLayoutStorageKey(hostContext), raw);
    return true;
  } catch {
    return false;
  }
}

export function clearTopologyLayout(hostContext: string, storage?: Pick<Storage, 'removeItem'>): void {
  try {
    const target = storage ?? window.localStorage;
    target.removeItem(topologyLayoutStorageKey(hostContext));
    target.removeItem(legacyTopologyLayoutStorageKey(hostContext));
  } catch { /* Storage may be disabled. */ }
}

export function defaultTopologyPosition(index: number): TopologyCanvasPoint {
  const column = index % 4;
  const row = Math.floor(index / 4);
  return { x: 36 + column * 310, y: 36 + row * 164 };
}

/** Deterministic first placement: connected groups first, isolated nodes afterwards. Existing positions always win. */
export function initialTopologyPositions(
  nodes: readonly Pick<TopologyCanvasNode, 'id' | 'height'>[],
  wires: readonly Pick<TopologyCanvasWire, 'source' | 'target'>[],
  existing: ReadonlyMap<TopologyNodeId, TopologyCanvasPoint> = new Map()
): Map<TopologyNodeId, TopologyCanvasPoint> {
  const ids = nodes.map((node) => node.id as TopologyNodeId).sort().slice(0, MAX_LAYOUT_NODES);
  const known = new Set(ids);
  const adjacency = new Map(ids.map((id) => [id, new Set<TopologyNodeId>()]));
  for (const wire of wires.slice(0, MAX_LAYOUT_WIRES)) {
    const source = wire.source.nodeId as TopologyNodeId;
    const target = wire.target.nodeId as TopologyNodeId;
    if (!known.has(source) || !known.has(target)) continue;
    adjacency.get(source)?.add(target);
    adjacency.get(target)?.add(source);
  }
  const visited = new Set<TopologyNodeId>();
  const groups: TopologyNodeId[][] = [];
  for (const start of ids) {
    if (visited.has(start)) continue;
    const pending = [start];
    const group: TopologyNodeId[] = [];
    visited.add(start);
    for (let cursor = 0; cursor < pending.length; cursor += 1) {
      const current = pending[cursor]!;
      group.push(current);
      for (const neighbor of [...(adjacency.get(current) ?? [])].sort()) {
        if (visited.has(neighbor)) continue;
        visited.add(neighbor);
        pending.push(neighbor);
      }
    }
    groups.push(group.sort());
  }
  groups.sort((a, b) => Number(b.length > 1) - Number(a.length > 1) || b.length - a.length || (a[0]! < b[0]! ? -1 : a[0]! > b[0]! ? 1 : 0));
  // Before bindings arrive an inventory may be entirely disconnected. Pack
  // those nodes as one grid instead of a provisional one-node-wide column.
  const firstIsolate = groups.findIndex(group => group.length === 1);
  if (firstIsolate >= 0 && groups.length - firstIsolate > 3) groups.push(groups.splice(firstIsolate).flat());
  const nodeById = new Map(nodes.map((node) => [node.id as TopologyNodeId, node]));
  const result = new Map<TopologyNodeId, TopologyCanvasPoint>([...existing].filter(([id]) => known.has(id)).map(([id, point]) => [id, { ...point }]));
  const placed = [...result].map(([id, point]) => ({ point, height: nodeById.get(id)?.height ?? TOPOLOGY_NODE_BOUNDS.height }));
  let groupY = 36;
  for (const group of groups) {
    const anchors = group.flatMap((id) => {
      const point = result.get(id);
      return point ? [{ id, point, height: nodeById.get(id)?.height ?? TOPOLOGY_NODE_BOUNDS.height }] : [];
    });
    const groupHasPositions = anchors.length > 0;
    const baseX = groupHasPositions ? Math.max(...anchors.map(({ point }) => point.x)) + TOPOLOGY_NODE_BOUNDS.width + 72 : 36;
    const baseY = groupHasPositions ? Math.min(...anchors.map(({ point }) => point.y)) : groupY;
    const unplaced = group.filter((id) => !result.has(id));
    const columns = Math.min(3, Math.max(1, unplaced.length));
    let maxY = groupY;
    let rowY = baseY;
    for (const [index, id] of unplaced.entries()) {
      const node = nodeById.get(id)!;
      const bounds = { width: TOPOLOGY_NODE_BOUNDS.width, height: node.height ?? topologyNodeHeight(0) };
      if (index > 0 && index % columns === 0) rowY = maxY + NODE_LAYOUT_GAP;
      const point = { x: baseX + (index % columns) * 310, y: rowY };
      let candidate = point;
      let row = 0;
      while (topologyPositionOverlaps(candidate, placed, NODE_LAYOUT_GAP, bounds.height)) {
        row += 1;
        candidate = { x: point.x, y: point.y + row * (bounds.height + NODE_LAYOUT_GAP) };
      }
      result.set(id, candidate);
      placed.push({ point: candidate, height: bounds.height });
      maxY = Math.max(maxY, candidate.y + bounds.height);
    }
    if (!groupHasPositions) groupY = maxY + TOPOLOGY_NODE_BOUNDS.height + NODE_LAYOUT_GAP;
  }
  return result;
}

export function topologyPositionOverlaps(
  point: TopologyCanvasPoint,
  existing: Iterable<TopologyCanvasPoint | { point: TopologyCanvasPoint; height: number }>,
  gap = NODE_LAYOUT_GAP,
  height: number = TOPOLOGY_NODE_BOUNDS.height
): boolean {
  return [...existing].some((candidate) => {
    const other = 'point' in candidate ? candidate.point : candidate;
    const otherHeight = 'point' in candidate && Number.isFinite(candidate.height)
      ? Math.max(1, candidate.height) : TOPOLOGY_NODE_BOUNDS.height;
    return point.x < other.x + TOPOLOGY_NODE_BOUNDS.width + gap
      && other.x < point.x + TOPOLOGY_NODE_BOUNDS.width + gap
      && point.y < other.y + otherHeight + gap
      && other.y < point.y + height + gap;
  });
}

export function pruneTopologyLayoutPositions(
  positions: ReadonlyMap<TopologyNodeId, TopologyCanvasPoint>,
  activeNodeIds: ReadonlySet<TopologyNodeId>
): Map<TopologyNodeId, TopologyCanvasPoint> {
  return new Map([...positions].filter(([nodeId]) => activeNodeIds.has(nodeId)).map(([nodeId, point]) => [nodeId, { ...point }]));
}
