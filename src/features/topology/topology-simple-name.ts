function buildFoldMap(): ReadonlyMap<number, string> {
  const folded = new Map<number, string>();
  for (const [first, last, stride, delta] of lowercaseRuns) {
    for (let unit: number = first; unit <= last; unit += stride) {
      folded.set(unit, String.fromCharCode(unit + delta));
    }
  }
  for (let i = 0; i < lowercasePairs.length; i += 2) {
    folded.set(lowercasePairs[i]!, String.fromCharCode(lowercasePairs[i + 1]!));
  }
  // Keep Java insertion order: the later A group overrides the first Ä row.
  for (const entry of transliterations) {
    const group = entry[0]!;
    const replacement = entry[1]!;
    for (let i = 0; i < group.length; i += 1) folded.set(group.charCodeAt(i), replacement);
  }
  return folded;
}

const folded = buildFoldMap();

function isNonAsciiJavaSpace(unit: number): boolean {
  // Character.isSpaceChar(char): Unicode separator categories, not JS \s.
  return unit === 0x00a0 || unit === 0x1680 || (unit >= 0x2000 && unit <= 0x200a)
    || unit === 0x2028 || unit === 0x2029 || unit === 0x202f || unit === 0x205f || unit === 0x3000;
}

/** Java SimpleName.getReducedForMatchingName(). An empty key is valid in Java,
 * but is not evidence of a usable topology name. */
export function javaSimpleNameKey(value: string): string {
  let key = '';
  let commentDepth = 0;
  let previous = 0;
  // Nodel.reduce then SimpleName.flatten. Both operate on UTF-16 units, and
  // everything reduce admits also passes flatten's filtering, so we fuse them.
  for (let i = 0; i < value.length; i += 1) {
    const unit = value.charCodeAt(i);
    if (unit === 0x28) { // (
      commentDepth += 1;
    } else if (commentDepth > 0) {
      if (unit === 0x29) commentDepth -= 1; // )
    } else if ((unit === 0x2d || unit === 0x2f) && unit === previous) { // -- or //
      break;
    } else if (unit > 0x7f) {
      if (!isNonAsciiJavaSpace(unit)) key += folded.get(unit) ?? value.charAt(i);
    } else if (unit >= 0x41 && unit <= 0x5a) {
      key += String.fromCharCode(unit + 32);
    } else if ((unit >= 0x61 && unit <= 0x7a) || (unit >= 0x30 && unit <= 0x39)) {
      key += value.charAt(i);
    }
    previous = unit;
  }
  return key;
}

/** Java SimpleName.equals(), including equality between two empty reductions. */
export function javaNodeNameEquals(left: string, right: string): boolean {
  return left === right || javaSimpleNameKey(left) === javaSimpleNameKey(right);
}
